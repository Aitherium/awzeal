#!/usr/bin/env python3
"""gen_oracle_h.py [fixtures dir] [out header] -- turn the Bonsai 2 codec oracles into a C header.

Inputs (written by AitherVeil kernels/__tests__/fixtures/gen_bonsai2_fixtures.py, a python
transcription of the PrismML llama.cpp fork):
  ptq1_0_oracle.json   64 PTQ1_0 blocks (bytes + dequant) and 6 K=512 ptq1_0 . q8_0 dots
  pq2_0_oracle.json    32 PQ2_0 blocks (bytes + codes + dequant); Q2_0 (type 42) is byte-identical
  fwht_oracle.json     n=1024 x, signs, H(s*x) in double

Q1_0 has no JSON oracle in that directory, so this file adds one, transcribed the same way from
the fork's Q1_0 rules as kernels/reference.ts states them (ggml-quants.c:40-71, quants.c:127-175):
  block = f16 d, u8 qs[16]; weight j = bit (qs[j>>3] >> (j&7)) & 1 ? +d : -d
  dot   = for each 128-block i: sumi = sum_k f32(d1_k * sum_b(+-q8)); sumf += f32(d0 * sumi)
Deterministic (seeded), pure stdlib. Writes LF line endings.
"""
import json
import random
import struct
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
FIX = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(
    "C:/AitherOS-Fresh/AitherOS/apps/AitherVeil/src/lib/bonsai-webgpu/kernels/__tests__/fixtures")
OUT = Path(sys.argv[2]) if len(sys.argv) > 2 else HERE.parent / "tests" / "oracle.h"


def f16r(x):
    return struct.unpack("<e", struct.pack("<e", x))[0]


def f32r(x):
    return struct.unpack("<f", struct.pack("<f", x))[0]


def cbytes(name, data):
    body = ",".join(str(b) for b in data)
    return f"static const unsigned char {name}[{len(data)}] = {{{body}}};\n"


def cfloats(name, vals, ctype="float"):
    body = ",".join(repr(float(v)) + ("f" if ctype == "float" else "") for v in vals)
    return f"static const {ctype} {name}[{len(vals)}] = {{{body}}};\n"


def cints(name, vals, ctype="int"):
    return f"static const {ctype} {name}[{len(vals)}] = {{{','.join(str(int(v)) for v in vals)}}};\n"


def q1_oracle(rng):
    blocks, dots = [], []
    for _ in range(32):
        d = f16r(0.05 + rng.random() * 2.0)
        bits = [rng.randint(0, 1) for _ in range(128)]
        qs = [0] * 16
        for j, b in enumerate(bits):
            qs[j >> 3] |= b << (j & 7)
        blk = struct.pack("<e", d) + bytes(qs)
        blocks.append((blk, [d if b else -d for b in bits]))
    for _ in range(6):
        K = 512
        row, signs, d0s = b"", [], []
        for _ in range(K // 128):
            d = f16r(0.1 + rng.random())
            bits = [rng.randint(0, 1) for _ in range(128)]
            qs = [0] * 16
            for j, b in enumerate(bits):
                qs[j >> 3] |= b << (j & 7)
            row += struct.pack("<e", d) + bytes(qs)
            signs.append([1 if b else -1 for b in bits])
            d0s.append(d)
        q8_d = [f16r(rng.random() * 0.02 + 0.001) for _ in range(K // 32)]
        q8_qs = [[rng.randint(-127, 127) for _ in range(32)] for _ in range(K // 32)]
        sumf = 0.0
        for i in range(K // 128):
            sumi = 0.0
            for k in range(4):
                sb = sum(signs[i][k * 32 + b] * q8_qs[i * 4 + k][b] for b in range(32))
                sumi = f32r(sumi + f32r(q8_d[i * 4 + k] * sb))
            sumf = f32r(sumf + f32r(d0s[i] * sumi))
        dots.append((row, q8_d, q8_qs, sumf))
    return blocks, dots


def main():
    ptq = json.loads((FIX / "ptq1_0_oracle.json").read_text())
    pq2 = json.loads((FIX / "pq2_0_oracle.json").read_text())
    fw = json.loads((FIX / "fwht_oracle.json").read_text())
    o = ["/* GENERATED by tools/gen_oracle_h.py -- do not edit. Sources: " + ptq["source"] + "; "
         + pq2["source"] + "; " + fw["source"] + "; Q1_0 transcribed in gen_oracle_h.py. */\n"]
    o.append(f"#define PTQ1_NB {len(ptq['blocks'])}\n")
    o.append(cbytes("ptq1_bytes", b"".join(bytes.fromhex(b["bytes"]) for b in ptq["blocks"])))
    o.append(cfloats("ptq1_deq", [v for b in ptq["blocks"] for v in b["dequant"]]))
    o.append(cints("ptq1_trits", [v for b in ptq["blocks"] for v in b["trits"]], "signed char"))
    o.append(f"#define PTQ1_ND {len(ptq['dots'])}\n#define PTQ1_K {ptq['dots'][0]['K']}\n")
    o.append(cbytes("ptq1_rows", b"".join(bytes.fromhex(d["row"]) for d in ptq["dots"])))
    o.append(cfloats("ptq1_q8d", [v for d in ptq["dots"] for v in d["q8_d"]]))
    o.append(cints("ptq1_q8qs", [v for d in ptq["dots"] for blk in d["q8_qs"] for v in blk], "signed char"))
    o.append(cfloats("ptq1_dot", [d["dot"] for d in ptq["dots"]]))
    o.append(f"#define PQ2_NB {len(pq2['blocks'])}\n")
    o.append(cbytes("pq2_bytes", b"".join(bytes.fromhex(b["bytes"]) for b in pq2["blocks"])))
    o.append(cfloats("pq2_deq", [v for b in pq2["blocks"] for v in b["dequant"]]))
    o.append(cints("pq2_codes", [v for b in pq2["blocks"] for v in b["codes"]], "unsigned char"))
    o.append(f"#define FW_N {fw['n']}\n")
    o.append(cfloats("fw_x", fw["x"]))
    o.append(cints("fw_s", fw["signs"], "signed char"))
    o.append(cfloats("fw_fwd", fw["forward_signed"], "double"))
    qb, qd = q1_oracle(random.Random(20261126))
    o.append(f"#define Q1_NB {len(qb)}\n")
    o.append(cbytes("q1_bytes", b"".join(b for b, _ in qb)))
    o.append(cfloats("q1_deq", [v for _, deq in qb for v in deq]))
    o.append(f"#define Q1_ND {len(qd)}\n#define Q1_K 512\n")
    o.append(cbytes("q1_rows", b"".join(r for r, _, _, _ in qd)))
    o.append(cfloats("q1_q8d", [v for _, d, _, _ in qd for v in d]))
    o.append(cints("q1_q8qs", [v for _, _, qs, _ in qd for blk in qs for v in blk], "signed char"))
    o.append(cfloats("q1_dot", [s for _, _, _, s in qd]))
    OUT.parent.mkdir(parents=True, exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("".join(o))
    print("wrote", OUT, OUT.stat().st_size, "bytes")


if __name__ == "__main__":
    main()
