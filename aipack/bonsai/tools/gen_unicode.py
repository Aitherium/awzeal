#!/usr/bin/env python3
"""gen_unicode.py <llama.cpp src/unicode-data.cpp> <out unicode_flags.h>

Reduce llama.cpp's codepoint flag table (MIT, generated from Unicode by
scripts/gen-unicode-data.py) to the four bits the qwen35 pre-tokenizer reads:
  1 = \\p{N}   2 = \\p{L}   4 = \\p{M}   8 = \\s (unicode_set_whitespace)   16 = any flag set
and emit merged ranges: uz_start[i] .. uz_start[i+1]-1 carry uz_flags[i].
"""
import re
import sys

MAXCP = 0x110000


def main(src, out):
    text = open(src, encoding="utf-8").read()
    m = re.search(r"unicode_ranges_flags = \{(.*?)\n\};", text, re.S)
    pairs = [(int(a, 16), int(b, 16)) for a, b in re.findall(r"\{0x([0-9A-Fa-f]+), 0x([0-9A-Fa-f]+)\}", m.group(1))]
    m = re.search(r"unicode_set_whitespace = \{(.*?)\n\};", text, re.S)
    ws = sorted(int(a, 16) for a in re.findall(r"0x([0-9A-Fa-f]+)", m.group(1)))
    assert pairs[0][0] == 0 and pairs[-1][0] == MAXCP
    # (start, reduced) boundaries
    bounds = {}
    for (s, f), (e, _) in zip(pairs, pairs[1:]):
        r = (1 if f & 0x2 else 0) | (2 if f & 0x4 else 0) | (4 if f & 0x10 else 0) | (16 if f else 0)
        bounds[s] = r
        bounds.setdefault(e, None)
    starts = sorted(k for k in bounds if k < MAXCP)

    def red(cp):
        lo = 0
        for s in starts:
            if s <= cp:
                lo = s
            else:
                break
        return bounds[lo]

    for c in ws:
        bounds[c] = (bounds[c] if bounds.get(c) is not None else red(c)) | 8 | 16
        if c + 1 not in bounds or bounds[c + 1] is None:
            bounds[c + 1] = red(c + 1)
    # rebuild a clean, ordered list (ws codepoints are isolated single-cp ranges)
    keys = sorted(k for k in bounds if k < MAXCP)
    vals = []
    cur = None
    for k in keys:
        v = bounds[k]
        if v is None:
            v = cur
        if k in ws:
            v = v | 8 | 16
        vals.append(v)
        if k not in ws:
            cur = v
    merged = []
    for k, v in zip(keys, vals):
        if merged and merged[-1][1] == v:
            continue
        merged.append((k, v))
    with open(out, "w", newline="\n") as f:
        f.write("/* generated by tools/gen_unicode.py from llama.cpp src/unicode-data.cpp (MIT) -- do not edit */\n")
        f.write(f"#define UZ_N {len(merged)}\n")
        f.write("static const unsigned int uz_start[UZ_N] = {\n")
        for i in range(0, len(merged), 10):
            f.write("  " + ",".join(f"0x{k:X}" for k, _ in merged[i:i + 10]) + ",\n")
        f.write("};\nstatic const unsigned char uz_flags[UZ_N] = {\n")
        for i in range(0, len(merged), 32):
            f.write("  " + ",".join(str(v) for _, v in merged[i:i + 32]) + ",\n")
        f.write("};\n")
    print(f"{len(pairs)} source ranges, {len(ws)} whitespace, {len(merged)} merged ranges")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
