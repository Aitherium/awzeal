#!/usr/bin/env python3
"""mkaikernel.py <src dir> <out AIKERNEL.ZC>

Bundle the fork's kernel AI layer so a STOCK ZealOS kernel can JIT it at
runtime: the AI section of Kernel/KernelA.HH (classes + defines), the
kernel_state global, FluxIDT.ZC, CapEngine.ZC, InferQueue.ZC and AgentForge.ZC.
Syscall is left out: it needs the INT 0x80 gate
that only a rebuilt kernel installs. Bytes are copied verbatim (cp437-safe).
"""
import sys

BEGIN = b"// ZealOS-AI: Agent Operating System Extensions"
END = b'#help_index ""'


def main(src: str, out: str) -> int:
    ka = open(f"{src}/Kernel/KernelA.HH", "rb").read()
    s = ka.find(BEGIN)
    e = ka.find(END, s)
    if s < 0 or e < 0:
        print("AI section markers not found in KernelA.HH", file=sys.stderr)
        return 1
    parts = [b"//AIKERNEL.ZC -- GENERATED by aipack/host/mkaikernel.py from src/Kernel. Do not edit.\n",
             b"//The fork's kernel AI layer, JIT-compiled at runtime on a stock ZealOS kernel.\n\n",
             ka[s:e], b"\n\nCKernelState kernel_state;\n\n"]
    for f in ("FluxIDT.ZC", "CapEngine.ZC", "InferQueue.ZC", "AgentForge.ZC"):
        parts += [f"\n//==== Kernel/{f} ====\n".encode(), open(f"{src}/Kernel/{f}", "rb").read(), b"\n"]
    data = b"".join(parts).replace(b"\r\n", b"\n")
    open(out, "wb").write(data)
    print(f"{out}: {len(data)} bytes")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1], sys.argv[2]))
